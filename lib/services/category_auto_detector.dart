  static CategoryAutoResult? detect(String title, [String description = '']) {
    final fullText = ' '.toLowerCase();
    if (fullText.trim().length < 3) return null;

    String? bestCategory;
    int maxMatches = 0;

    _categoryKeywords.forEach((catId, keywords) {
      int matches = 0;
      for (final kw in keywords) {
        if (fullText.contains(kw)) {
          matches += (kw.length >= 6 ? 2 : 1);
        }
      }
      if (matches > maxMatches) {
        maxMatches = matches;
        bestCategory = catId;
      }
    });

    if (bestCategory == null || maxMatches == 0) {
      return null;
    }

    String? bestSubCategory;
    final subMap = _subCategoryKeywords[bestCategory];
    if (subMap != null) {
      int maxSubMatches = 0;
      subMap.forEach((subId, subKwList) {
        int subMatches = 0;
        for (final kw in subKwList) {
          if (fullText.contains(kw)) {
            subMatches += (kw.length >= 6 ? 2 : 1);
          }
        }
        if (subMatches > maxSubMatches) {
          maxSubMatches = subMatches;
          bestSubCategory = subId;
        }
      });
    }

    final matchedCat = CategoryData.categories.firstWhere(
      (c) => c.id.toLowerCase() == bestCategory!.toLowerCase() || c.ru.toLowerCase() == bestCategory!.toLowerCase(),
      orElse: () => CategoryData.categories.first,
    );

    return CategoryAutoResult(
      categoryId: matchedCat.id,
      subCategoryId: bestSubCategory,
      confidence: (maxMatches >= 3 ? 0.95 : 0.8),
    );
  }
