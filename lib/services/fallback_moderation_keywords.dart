// ─────────────────────────────────────────────────────────────────────────────
// НОРМАЛИЗАТОР ТЕКСТА
//
// Задача: привести текст к канонической форме перед сравнением со стоп-словами,
// чтобы обойти типичные попытки обфускации:
//   "НАРК0ТИК"   → "наркотик"   (0 → о)
//   "а1коголь"   → "аикоголь"   (1 → и)  ← не в словаре, пример нормализации
//   "о-р-у-ж-и-е" → "оружие"   (удаление разделителей)
// ─────────────────────────────────────────────────────────────────────────────
class ModerationNormalizer {
  ModerationNormalizer._();

  /// Карта замен цифр-омоглифов на кириллические буквы.
  /// Охватывает типичный «leet speak» на кириллице.
  static const Map<String, String> _leetMap = {
    '0': 'о',   // 0 → о  (НАРК0ТИК → НАРКОТИК)
    '3': 'з',   // 3 → з
    '4': 'ч',   // 4 → ч  (4ерт → черт)
    '6': 'б',   // 6 → б
    '1': 'и',   // 1 → и  (1нтим → интим, а1коголь → аикоголь*)
    '@': 'а',   // @ → а
    '$': 'с',   // $ → с
    '!': 'и',   // ! → и
  };

  /// Нормализует строку перед сравнением со стоп-словами:
  /// 1. toLowerCase()
  /// 2. Замена цифр-омоглифов (leet): 0→о, 3→з, 4→ч, 6→б, 1→и
  /// 3. Удаление разделителей внутри слов: дефис, точка, подчёркивание,
  ///    пробельные символы между одиночными буквами ("о р у ж и е" → "оружие")
  ///
  /// ВАЖНО: пробел между многосложными словами НЕ удаляется, чтобы не склеивать
  ///   "торговля людьми" в "торговлялюдьми". Пробел убирается только если с обеих
  ///   сторон стоят одиночные символы (т.е. окружены пробелами или краями строки).
  static String normalize(String input) {
    // Шаг 1: нижний регистр
    String s = input.toLowerCase();

    // Шаг 2: замена leet-символов
    for (final entry in _leetMap.entries) {
      s = s.replaceAll(entry.key, entry.value);
    }

    // Шаг 3а: удаление ЖЁСТКИХ разделителей (дефис, точка, подчёркивание,
    //   звёздочка) между любыми непробельными символами.
    //   Итеративно: "о-р-у-ж-и-е" → за 5 проходов → "оружие"
    String prev;
    do {
      prev = s;
      s = s.replaceAllMapped(
        RegExp(r'(\S)([-._*])(\S)'),
        (m) => '${m[1]}${m[3]}',
      );
    } while (s != prev);

    // Шаг 3б: удаление ПРОБЕЛА только между одиночными символами.
    // Разбираем строку по пробелам, соединяем последовательности букв длины 1.
    // Это преобразует "з а к л а д к а" -> "закладка", но оставляет "торговля людьми".
    final words = s.split(' ');
    final collapsed = <String>[];
    var currentSingleChars = <String>[];

    for (final word in words) {
      if (word.isEmpty) continue;
      if (word.length == 1) {
        currentSingleChars.add(word);
      } else {
        if (currentSingleChars.isNotEmpty) {
          collapsed.add(currentSingleChars.join(''));
          currentSingleChars = [];
        }
        collapsed.add(word);
      }
    }
    if (currentSingleChars.isNotEmpty) {
      collapsed.add(currentSingleChars.join(''));
    }
    s = collapsed.join(' ');

    return s;
  }
}
