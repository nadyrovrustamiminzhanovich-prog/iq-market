  /// Возвращает список всех Q&A в виде форматированной строки
  static String getFaqContext(String mode, String lang) {
    final Map<String, List<Map<String, dynamic>>> source =
        lang == 'KZ' ? faqKz : (lang == 'UG' ? faqUyg : faqRu);
    final List<Map<String, dynamic>> list = source[mode] ?? [];

    final buffer = StringBuffer();
    buffer.writeln("БАЗА ОТВЕТОВ:");
    for (var i = 0; i < list.length; i++) {
      buffer.writeln("${i + 1}. Вопрос: ${list[i]['q']}");
      buffer.writeln("   Ответ: ${list[i]['a']}");
    }
    return buffer.toString();
  }

  /// Поиск ответа по текстовому совпадению ключевых слов и тегов (для мгновенного матчинга)
  static Map<String, String>? findExactMatch(
      String query, String mode, String lang) {
    final Map<String, List<Map<String, dynamic>>> source =
        lang == 'KZ' ? faqKz : (lang == 'UG' ? faqUyg : faqRu);
    final List<Map<String, dynamic>> list = source[mode] ?? [];

    final cleanQuery = query.toLowerCase().trim();
    if (cleanQuery.isEmpty) return null;

    Map<String, dynamic>? bestMatch;
    int maxOverlap = 0;

    // Очищаем запрос от знаков препинания и делим на слова
    final queryWords = cleanQuery
        .replaceAll(RegExp(r'[^\w\sа-яёәіңғүұқөһҗقغڭژئی]'), '')
        .split(' ')
        .map((w) => w.trim())
        .where((w) => w.length > 2)
        .toList();

    for (final item in list) {
      final qLower = item['q']!.toLowerCase();
      final List<String> tags = List<String>.from(item['tags'] ?? []);

      // 1. Прямое совпадение по заголовку вопроса
      if (qLower.contains(cleanQuery) || cleanQuery.contains(qLower)) {
        return {'q': item['q']!, 'a': item['a']!};
      }

      // 2. Поиск по списку ключевых тегов с проверкой корней слов (для гибкости)
      int overlap = 0;
      for (final word in queryWords) {
        final wordStem = word.length > 4 ? word.substring(0, 4) : word;

        for (final tag in tags) {
          final tagLower = tag.toLowerCase();
          final tagStem = tagLower.length > 4 ? tagLower.substring(0, 4) : tagLower;

          if (word == tagLower || word.contains(tagLower) || tagLower.contains(word)) {
            overlap += 3; // Точное или близкое совпадение
          } else if (wordStem == tagStem) {
            overlap += 2; // Совпадение корней (например, "регистр")
          }
        }
        if (qLower.contains(word)) {
          overlap += 1;
        }
      }

      if (overlap > maxOverlap && overlap >= 2) {
        maxOverlap = overlap;
        bestMatch = item;
      }
    }

    if (bestMatch != null) {
      return {'q': bestMatch['q']!, 'a': bestMatch['a']!};
    }
    return null;
  }
