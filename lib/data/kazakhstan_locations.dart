    'Другие города': [
      'Астана', 'Караганда', 'Актобе', 'Уральск', 'Тараз', 'Кызылорда', 'Актау', 'Атырау', 'Павлодар', 'Петропавловск', 'Семей'
    ]
  };

  // Метод для получения короткого названия (без скобок и лишних слов)
  static String getShortName(String location) {
    if (location.contains('(')) {
      return location.split('(')[0].trim();
    }
    if (location.contains('город')) {
      return location.replaceAll(' (город)', '').trim();
    }
    if (location == 'Шонжы') return 'Чунджа';
    return location;
  }

  // Плоский список для поиска
  static List<String> getAllLocations() {
    List<String> all = ['Чунджа'];
    hierarchy.forEach((key, cities) {
      for (var city in cities) {
        all.add(getShortName(city));
      }
    });
    return all.toSet().toList()..sort();
  }
}
