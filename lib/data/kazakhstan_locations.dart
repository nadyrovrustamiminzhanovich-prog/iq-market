class KazakhstanLocations {
  // Иерархия городов и районов по запросу пользователя (Очищенная от скобок)
  static const Map<String, List<String>> hierarchy = {
    'Уйгурский район': [
      'Чунджа', 'Ават', 'Актам', 'Бахар', 'Долайты', 'Галжат', 
      'Довун', 'Кетмень', 'Сумбе', 'Тирмен', 'Аксу', 'Карасу', 'Байсеит', 'Кокпек'
    ],
    'Жаркент': [
      'Жаркент', 'Актам', 'Ават', 'Айдарлы', 'Баскуншы', 'Коныролен', 'Хоргос', 'Пиджим'
    ],
    'Енбекшиказахский район': [
      'Чилик', 'Есик', 'Талгар', 'Маловодное', 'Нура', 'Каратурык', 'Лавар'
    ],
    'Алматы': [
      'Алматы', 'Гульдала', 'Дружба', 'Бесагаш', 'Туздыбастау', 'Боралдай', 
      'Каскелен', 'Узынагаш', 'Шамалган', 'Отеген Батыр', 'Конаев'
    ],
    'Шымкент': [
      'Шымкент', 'Кентау', 'Арыс', 'Сарыагаш', 'Ленгер'
    ],
    'Туркестан': [
      'Туркестан', 'Кентау', 'Жетысай', 'Шардара', 'Тюлькубас'
